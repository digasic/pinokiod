const CYRILLIC_RE = /[\u0400-\u04FF]/;

/**
 * Decode common HTML entities for matching.
 * Keep &#10; (and numeric entities) as-is in the key per catalog rules.
 */
function decodeEntities(s) {
  return String(s)
    .replace(/&apos;/gi, "'")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&amp;/gi, "&")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&nbsp;/gi, "\u00a0")
    .replace(/&times;/gi, "\u00d7");
}

function isCorruptKey(key) {
  return CYRILLIC_RE.test(key);
}

function isTechnicalJunk(line) {
  const s = line.trim();
  if (!s) return true;
  // HTML fragment leftovers from imperfect literal extraction
  if (/^["']?\s*(target|href|data-|class|style)=/i.test(s)) return true;
  if (/^["']?\s*>/.test(s)) return true;
  if (/^["']?\s*\?/.test(s) && s.includes('">')) return true;
  if (s.startsWith('" ') || s.startsWith("' ")) return true;
  if (/^["']\s*(target|_blank|href)/i.test(s)) return true;
  if (s === "&times;" || s === "&gt;" || s === "&nbsp;or&nbsp;") return true;
  if (/^['"] class=/i.test(s)) return true;
  if (s.includes('">') && (s.startsWith('"') || s.startsWith("'") || s.startsWith("?"))) return true;
  if (/^>/.test(s) && s.length < 40) return true;
  if (s === "full-title" || s === "plugin-repo" || s === "task-repo" || s === "start.js") return true;
  if (s === "dal" || s === "my-org" || s === "Index3") return true;
  return false;
}

function lookup(dict, key) {
  if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
  const decoded = decodeEntities(key);
  if (decoded !== key && Object.prototype.hasOwnProperty.call(dict, decoded)) {
    return dict[decoded];
  }
  // Also try encoding apostrophe back for keys that store &apos;
  if (decoded.includes("'")) {
    const encoded = decoded.replace(/'/g, "&apos;");
    if (Object.prototype.hasOwnProperty.call(dict, encoded)) return dict[encoded];
  }
  return undefined;
}

function sortKeys(keys) {
  return keys.sort((a, b) => {
    if (b.length !== a.length) return b.length - a.length;
    return a.localeCompare(b);
  });
}

function main() {
  const oldRu = JSON.parse(fs.readFileSync(RU_JSON, "utf8"));
  const literals = fs
    .readFileSync(LITERALS, "utf8")
    .split(/\r?\n/)
    .map((l) => l.trimEnd())
    .filter((l) => l.length > 0);

  /** @type {Record<string, string>} */
  const catalog = {};

  // 1) Seed from manual (authoritative)
  for (const [k, v] of Object.entries(manual)) {
    if (isCorruptKey(k)) continue;
    if (typeof v !== "string" || !v) continue;
    catalog[k] = v;
    // Also store decoded form for matching &apos; variants
    const dec = decodeEntities(k);
    if (dec !== k && !isCorruptKey(dec)) {
      catalog[dec] = v;
    }
  }

  // 2) Merge old ru.json — skip corrupt keys / empty
  for (const [k, v] of Object.entries(oldRu)) {
    if (isCorruptKey(k)) continue;
    if (typeof v !== "string" || !v) continue;
    // Prefer manual when both exist
    if (Object.prototype.hasOwnProperty.call(manual, k)) continue;
    if (Object.prototype.hasOwnProperty.call(manual, decodeEntities(k))) continue;
    if (!Object.prototype.hasOwnProperty.call(catalog, k)) {
      catalog[k] = v;
    }
  }

  // Coverage against literals
  let translated = 0;
  const missing = [];
  for (const lit of literals) {
    if (isTechnicalJunk(lit)) {
      // count as "skipped", not missing for user-facing coverage
      continue;
    }
    const hit = lookup(catalog, lit);
    if (hit !== undefined) {
      translated += 1;
      // Ensure the exact literal key exists in output (preserve original form)
      if (!Object.prototype.hasOwnProperty.call(catalog, lit)) {
        catalog[lit] = hit;
      }
    } else {
      missing.push(lit);
    }
  }

  const userFacing = literals.filter((l) => !isTechnicalJunk(l));
  const totalUF = userFacing.length;
  const pct = totalUF ? ((translated / totalUF) * 100).toFixed(1) : "0.0";

  // Write sorted catalog
  const sorted = {};
  for (const k of sortKeys(Object.keys(catalog))) {
    sorted[k] = catalog[k];
  }
  fs.writeFileSync(RU_JSON, JSON.stringify(sorted, null, 2) + "\n", "utf8");

  const reportLines = [
    `ru-coverage report`,
    `generated: ${new Date().toISOString()}`,
    ``,
    `total ejs-literals: ${literals.length}`,
    `user-facing (excl. technical/HTML junk): ${totalUF}`,
    `translated (user-facing): ${translated}`,
    `missing (user-facing): ${missing.length}`,
    `coverage: ${pct}%`,
    `catalog keys written: ${Object.keys(sorted).length}`,
    `ru.json: ${RU_JSON}`,
    ``,
    `--- missing (first 100) ---`,
    ...missing.slice(0, 100).map((m, i) => `${i + 1}. ${m}`),
  ];
  fs.writeFileSync(REPORT, reportLines.join("\n") + "\n", "utf8");

  console.log(`Wrote ${Object.keys(sorted).length} keys -> ${RU_JSON}`);
  console.log(`Coverage: ${translated}/${totalUF} user-facing (${pct}%) of ${literals.length} literals`);
  console.log(`Missing: ${missing.length} (see ${REPORT})`);
  if (translated / Math.max(totalUF, 1) < 0.8) {
    console.warn("WARNING: coverage below 80%");
    process.exitCode = 1;
  }
}

